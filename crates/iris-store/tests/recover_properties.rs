//! Seeded property tests of recovery: a recording written by the writer and
//! then damaged at a generated offset recovers to exactly the fragments that
//! end before the damage, with a sidecar bound to it, and recovering again
//! changes nothing.

use std::fs::{self, File, OpenOptions};
use std::os::unix::fs::FileExt as _;
use std::path::{Path, PathBuf};
use std::sync::Arc;
use std::time::Duration;

use bytes::Bytes;
use iris_core::id::{CameraId, StreamKey, StreamKind};
use iris_core::time::WallUs;
use iris_mp4::fragment::{Fragment, Sample};
use iris_mp4::index::{
    FLAG_DISCONTINUITY_BEFORE, MAX_PERSISTED_INDEX_RECORDS, read_index_file_bound_to_media,
};
use iris_mp4::init::SampleEntry;
use iris_mp4::reader::{self, FragmentInfo, ScanOptions, ScanReport};
use iris_store::recover::{RecoveryReport, recover_segment};
use iris_store::{StoragePolicy, WriterHandle};

/// A small deterministic generator (xorshift64*), so a failure reproduces
/// from its seed.
struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        self.0 ^= self.0 >> 12;
        self.0 ^= self.0 << 25;
        self.0 ^= self.0 >> 27;
        self.0.wrapping_mul(0x2545_f491_4f6c_dd1d)
    }

    /// A value in `0..n`.
    fn below(&mut self, n: u64) -> u64 {
        self.next() % n
    }

    fn bytes(&mut self, len: usize) -> Vec<u8> {
        (0..len).map(|_| self.next().to_le_bytes()[0]).collect()
    }
}

/// How the tail of the media file is damaged from an offset on.
#[derive(Clone, Copy, Debug)]
enum Damage {
    /// The file ends there.
    Cut,
    /// Zeros to the end the file had, as unwritten preallocated space reads.
    Zeros,
    /// Generated bytes to the end the file had.
    Noise,
}

/// What happens to the sidecar beside the damaged media.
#[derive(Clone, Copy, Debug)]
enum Sidecar {
    Intact,
    Missing,
    /// Cut at a generated length.
    Cut,
    /// Generated bytes appended.
    Noise,
}

fn fragment(index: u64, rng: &mut Rng, entry: &Arc<SampleEntry>) -> Fragment {
    let samples = (0..=rng.below(5))
        .map(|sample| {
            // One length-prefixed NAL: a two-byte header and filler.
            let nal_len = 2 + u32::try_from(rng.below(3000)).unwrap();
            let mut data = nal_len.to_be_bytes().to_vec();
            data.extend_from_slice(&[if sample == 0 { 0x26 } else { 0x02 }, 1]);
            data.resize(4 + usize::try_from(nal_len).unwrap(), 0xaa);
            Sample {
                data: Bytes::from(data),
                duration: 3000,
                is_sync: sample == 0,
            }
        })
        .collect();
    Fragment {
        samples,
        decode_time: index * 18_000,
        wall: WallUs::new((1_793_460_958 + i64::try_from(index).unwrap()) * 1_000_000),
        raw_rtp: 42,
        new_run: index == 0,
        sample_entry: Arc::clone(entry),
    }
}

/// Writes one sealed recording of two to nine fragments and returns its path.
fn recording(root: &Path, rng: &mut Rng) -> PathBuf {
    let entry = Arc::new(SampleEntry::new(
        Bytes::from_static(b"\0\0\0\x10hvc1\0\0\0\0\0\0\0\0"),
        "hvc1.1.6.L150.B0".into(),
        640,
        480,
    ));
    let policy = StoragePolicy {
        sync_interval: Duration::from_millis(50),
        preallocate_bytes: 1 << 16,
        rotate_bytes: 1 << 30,
        rotate_age: Duration::from_secs(3600),
    };
    let writer = WriterHandle::spawn(root.to_path_buf(), policy, 16).unwrap();
    let key = StreamKey {
        camera: CameraId::try_new("cam1").unwrap(),
        kind: StreamKind::Main,
    };
    for index in 0..2 + rng.below(8) {
        writer
            .try_send(key.clone(), fragment(index, rng, &entry))
            .unwrap();
    }
    writer.shutdown().unwrap();
    let mut found = Vec::new();
    let mut pending = vec![root.to_path_buf()];
    while let Some(dir) = pending.pop() {
        for entry in fs::read_dir(dir).unwrap() {
            let path = entry.unwrap().path();
            if path.is_dir() {
                pending.push(path);
            } else if path.extension().is_some_and(|x| x == "mp4") {
                found.push(path);
            }
        }
    }
    assert_eq!(found.len(), 1, "one recording");
    found.remove(0)
}

fn scanned(path: &Path) -> ScanReport {
    reader::scan(
        File::open(path).unwrap(),
        ScanOptions {
            verify_crc: true,
            collect_samples: false,
        },
    )
    .unwrap()
}

/// Damages the media file from `offset` to its end.
fn damage_media(media: &Path, original: &[u8], offset: u64, damage: Damage, rng: &mut Rng) {
    let file = OpenOptions::new().write(true).open(media).unwrap();
    let at = usize::try_from(offset).unwrap();
    let tail = original.len() - at;
    match damage {
        Damage::Cut => file.set_len(offset).unwrap(),
        Damage::Zeros => file.write_all_at(&vec![0; tail], offset).unwrap(),
        Damage::Noise => {
            // A first byte that differs, so the damage starts at `offset`.
            let mut noise = rng.bytes(tail);
            noise[0] = !original[at];
            file.write_all_at(&noise, offset).unwrap();
        }
    }
}

fn damage_sidecar(index: &Path, sidecar: Sidecar, rng: &mut Rng) {
    let open = || OpenOptions::new().write(true).open(index).unwrap();
    match sidecar {
        Sidecar::Intact => {}
        Sidecar::Missing => fs::remove_file(index).unwrap(),
        Sidecar::Cut => {
            let index_len = fs::metadata(index).unwrap().len();
            open().set_len(rng.below(index_len + 1)).unwrap();
        }
        Sidecar::Noise => {
            let index_len = fs::metadata(index).unwrap().len();
            let noise_len = 1 + usize::try_from(rng.below(100)).unwrap();
            open()
                .write_all_at(&rng.bytes(noise_len), index_len)
                .unwrap();
        }
    }
}

/// The report's wall and media bounds are those of the recovered fragments,
/// and zero when none was recovered.
fn check_report_bounds(report: &RecoveryReport, expected: &[&FragmentInfo], context: &str) {
    let bounds = (
        report.wall_start,
        report.wall_end,
        report.media_start,
        report.media_end,
    );
    let (Some(first), Some(last)) = (expected.first(), expected.last()) else {
        assert_eq!(
            bounds,
            (WallUs::default(), WallUs::default(), 0, 0),
            "{context}"
        );
        return;
    };
    let last_wall = last.wall.expect("the writer stamps every fragment");
    assert_eq!(
        bounds,
        (
            first.wall.expect("the writer stamps every fragment"),
            last_wall.offset(i64::from(last.duration) * 100 / 9),
            first.decode_time,
            last.decode_time + u64::from(last.duration),
        ),
        "{context}"
    );
}

#[test]
fn a_damaged_recording_recovers_to_the_fragments_before_the_damage() {
    for seed in 1..=300 {
        let mut rng = Rng(seed);
        let dir = tempfile::tempdir().unwrap();
        let media = recording(dir.path(), &mut rng);
        let index = media.with_extension("idx");
        let clean = scanned(&media);
        assert_eq!(clean.stop, None, "seed {seed}");
        let original = fs::read(&media).unwrap();
        let len = original.len() as u64;
        let init_len = u64::from(clean.init_len);
        let (_, written) = read_index_file_bound_to_media(
            File::open(&index).unwrap(),
            MAX_PERSISTED_INDEX_RECORDS,
            &clean,
            len,
        )
        .unwrap()
        .expect("the writer's sidecar is bound");
        assert_ne!(
            written[0].flags & FLAG_DISCONTINUITY_BEFORE,
            0,
            "seed {seed}"
        );
        assert!(
            written.iter().all(|record| record.raw_rtp == 42),
            "seed {seed}"
        );

        // Damage from an offset at or after the initialization segment.
        let offset = init_len + rng.below(len - init_len);
        let damage = [Damage::Cut, Damage::Zeros, Damage::Noise][rng.below(3) as usize];
        damage_media(&media, &original, offset, damage, &mut rng);
        let sidecar = [
            Sidecar::Intact,
            Sidecar::Missing,
            Sidecar::Cut,
            Sidecar::Noise,
        ][rng.below(4) as usize];
        damage_sidecar(&index, sidecar, &mut rng);
        let context = format!("seed {seed}: {damage:?} at {offset} of {len}, sidecar {sidecar:?}");

        // The fragments whose bytes the damage left alone, as a prefix:
        // zeros over a trailer's reserved bytes change nothing.
        let damaged = fs::read(&media).unwrap();
        let expected: Vec<_> = clean
            .fragments
            .iter()
            .take_while(|fragment| {
                let start = usize::try_from(fragment.offset).unwrap();
                let end = start + usize::try_from(fragment.len).unwrap();
                damaged.get(start..end) == Some(&original[start..end])
            })
            .collect();
        let expected_len = expected
            .last()
            .map_or(init_len, |last| last.offset + u64::from(last.len));

        let report = recover_segment(&media).unwrap_or_else(|error| panic!("{context}: {error}"));
        assert_eq!(report.fragments, expected.len(), "{context}");
        assert_eq!(report.valid_len, expected_len, "{context}");
        let recovered = fs::read(&media).unwrap();
        assert_eq!(
            recovered,
            original[..usize::try_from(expected_len).unwrap()],
            "{context}: the valid prefix is untouched"
        );
        let after = scanned(&media);
        assert_eq!(after.stop, None, "{context}");
        assert_eq!(after.fragments.len(), expected.len(), "{context}");
        let bound = read_index_file_bound_to_media(
            File::open(&index).unwrap(),
            MAX_PERSISTED_INDEX_RECORDS,
            &after,
            expected_len,
        )
        .unwrap_or_else(|error| panic!("{context}: {error}"));
        let (_, records) = bound.unwrap_or_else(|| panic!("{context}: the sidecar is not bound"));
        assert_eq!(records.len(), expected.len(), "{context}");
        check_report_bounds(&report, &expected, &context);
        assert_eq!(u64::from(report.init_len), init_len, "{context}");
        assert_eq!(report.original_len, damaged.len() as u64, "{context}");
        assert_eq!(
            report.truncated,
            expected_len < damaged.len() as u64,
            "{context}"
        );
        // What only the sidecar knows (the run boundary and the raw RTP
        // timestamps) survives when the sidecar did, and is absent when a
        // scan alone rebuilt the records.
        match sidecar {
            Sidecar::Intact => assert_eq!(records, written[..records.len()], "{context}"),
            Sidecar::Missing => {
                assert!(
                    records.iter().all(|record| record.raw_rtp == 0
                        && record.flags & FLAG_DISCONTINUITY_BEFORE == 0),
                    "{context}"
                );
            }
            Sidecar::Cut | Sidecar::Noise => {}
        }

        // Recovering a recovered recording changes nothing.
        let index_bytes = fs::read(&index).unwrap();
        let again = recover_segment(&media).unwrap_or_else(|error| panic!("{context}: {error}"));
        assert_eq!(again.fragments, report.fragments, "{context}");
        assert_eq!(again.valid_len, report.valid_len, "{context}");
        assert_eq!(fs::read(&media).unwrap(), recovered, "{context}");
        assert_eq!(fs::read(&index).unwrap(), index_bytes, "{context}");
    }
}
