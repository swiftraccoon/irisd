//! The decoder configuration of an `mp4a` init segment that ffmpeg wrote: a
//! check of the `esds` reader against a muxer other than the daemon's. The
//! daemon writes each descriptor length in the fewest bytes that hold it;
//! ffmpeg writes every length in four.
//!
//! `MP4A_INIT` is the `ftyp` and `moov` boxes, the first 696 bytes, of a
//! fragmented MP4. ffmpeg wrote it with its AAC encoder from 0.1 s of a
//! synthetic 440 Hz tone at 48 kHz in two channels.
//! `docs/research/15-apple-clients.md` §11 records the version of ffmpeg and
//! the date. The command:
//!
//! ```text
//! ffmpeg -f lavfi -i sine=frequency=440:sample_rate=48000:duration=0.1 -ac 2 \
//!     -c:a aac -b:a 128k -movflags +frag_keyframe+empty_moov \
//!     -fflags +bitexact -flags:a +bitexact -map_metadata -1 -f mp4 mp4a.mp4
//! ```
//!
//! The tests expect what ffprobe reports for the stream:
//!
//! ```text
//! ffprobe -v error -show_streams -show_data mp4a.mp4
//! ```
//!
//! It reports `codec_tag_string=mp4a`, `profile=LC`, `sample_rate=48000`,
//! `channels=2`, and five bytes of extradata, `1190 56e5 00`.

