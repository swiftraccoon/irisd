/// The `AudioSpecificConfig` that ffprobe reports as the stream's extradata.
const FFPROBE_EXTRADATA: [u8; 5] = [0x11, 0x90, 0x56, 0xe5, 0x00];

/// The AAC configuration that `DecoderConfig::parse` reads from `MP4A_INIT`.
fn ffmpegs_aac_config() -> AacConfig {
    for tag in [0x03, 0x04, 0x05] {
        assert!(
            MP4A_INIT
                .windows(4)
                .any(|window| window == [tag, 0x80, 0x80, 0x80]),
            "the fixture's descriptor of tag {tag} has a length of four bytes"
        );
    }
    match DecoderConfig::parse(&MP4A_INIT) {
        Ok(DecoderConfig::Aac(config)) => config,
        other => panic!("not AAC: {other:?}"),
    }
}

#[test]
fn ffmpegs_mp4a_init_segment_gives_the_audio_specific_config_ffprobe_reports() {
    assert_eq!(
        ffmpegs_aac_config().audio_specific_config(),
        FFPROBE_EXTRADATA
    );
}

#[test]
fn ffmpegs_mp4a_init_segment_gives_the_sampling_rate_ffprobe_reports() {
    assert_eq!(ffmpegs_aac_config().sample_rate(), 48_000);
}

#[test]
fn ffmpegs_mp4a_init_segment_gives_the_channel_count_ffprobe_reports() {
    assert_eq!(ffmpegs_aac_config().channels(), 2);
}
