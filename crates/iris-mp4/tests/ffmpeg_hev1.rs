/// The HEVC configuration `DecoderConfig::parse` reads from `HEV1_INIT`.
fn ffmpegs_hevc_config() -> HevcConfig {
    assert!(
        HEV1_INIT.windows(4).any(|window| window == b"hev1"),
        "the fixture's sample entry is an hev1 entry"
    );
    match DecoderConfig::parse(&HEV1_INIT) {
        Ok(DecoderConfig::Hevc(config)) => config,
        other => panic!("not HEVC: {other:?}"),
    }
}

#[test]
fn ffmpegs_hev1_init_segment_gives_hevc_at_its_picture_size() {
    let config = ffmpegs_hevc_config();
    assert_eq!((config.width(), config.height()), (64, 64));
}

#[test]
fn ffmpegs_hev1_init_segment_gives_hevc_with_the_sets_ffmpeg_reads() {
    assert_eq!(
        ffmpegs_hevc_config().parameter_sets(),
        FFMPEG_PARAMETER_SETS
    );
}

#[test]
fn parse_parameter_sets_gives_the_sets_ffmpeg_reads_from_its_hev1_init_segment() {
    assert_eq!(
        parse_parameter_sets(&HEV1_INIT),
        Ok(FFMPEG_PARAMETER_SETS.map(<[u8]>::to_vec).to_vec())
    );
}
