//! The decoder configuration of an `hev1` init segment that ffmpeg wrote: a
//! check of the reader against a muxer other than the daemon's, which writes
//! `hvc1` alone.
//!
//! `HEV1_INIT` is the `ftyp` and `moov` boxes, the first 820 bytes, of the
//! fragmented MP4 that ffmpeg wrote with libx265 from one synthetic frame of
//! its test pattern, 64×64 in 4:2:0. `docs/research/15-apple-clients.md` §11
//! records the versions of ffmpeg and libx265 and the date. The command:
//!
//! ```text
//! ffmpeg -f lavfi -i testsrc=size=64x64:rate=1 -frames:v 1 -pix_fmt yuv420p \
//!     -c:v libx265 -x265-params log-level=error:info=0 -tag:v hev1 \
//!     -movflags +frag_keyframe+empty_moov -fflags +bitexact \
//!     -flags:v +bitexact -map_metadata -1 -f mp4 hev1.mp4
//! ```
//!
//! Its `hvcC` holds a VPS, an SPS, and a PPS, each in an array whose
//! `array_completeness` bit is clear. `FFMPEG_PARAMETER_SETS` are the NAL
//! units that ffmpeg's reader of the record put before the frame when it
//! rewrote the file as an Annex B stream, in that stream's order:
//!
//! ```text
//! ffmpeg -i hev1.mp4 -c:v copy -bsf:v hevc_mp4toannexb -f hevc annexb.hevc
//! ```

